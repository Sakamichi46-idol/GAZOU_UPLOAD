def normalize_tag_text(value: str) -> str:
    text = unicodedata.normalize("NFKC", str(value or "")).strip().casefold()
    text = re.sub(r"[\s　]+", "", text)
    text = text.replace("／", "/").replace("・", "")
    return text


def aliases_for_canonical(canonical: str) -> tuple[str, ...]:
    key = normalize_tag_text(canonical)
    for tag_map in SEARCH_TAG_ALIASES.values():
        for label, aliases in tag_map.items():
            normalized = {normalize_tag_text(label), *(normalize_tag_text(v) for v in aliases)}
            if key in normalized:
                return tuple(dict.fromkeys((label, *aliases)))
    return (str(canonical).strip(),) if str(canonical).strip() else ()


def match_canonical_tag(query: str) -> list[tuple[str, str]]:
    clean = normalize_tag_text(query)
    if not clean:
        return []
    exact: list[tuple[str, str]] = []
    partial: list[tuple[str, str]] = []
    for category, tag_map in SEARCH_TAG_ALIASES.items():
        for label, aliases in tag_map.items():
            values = (label, *aliases)
            normalized_values = [normalize_tag_text(value) for value in values]
            if clean in normalized_values:
                exact.append((category, label))
            elif clean in normalize_tag_text(label):
                partial.append((category, label))
    return exact + partial


def build_curated_index(raw_tag_ids: dict[str, set[int]]) -> dict[str, dict[str, set[int]]]:
    normalized_raw: dict[str, set[int]] = {}
    for raw_tag, image_ids in raw_tag_ids.items():
        normalized_raw.setdefault(normalize_tag_text(raw_tag), set()).update(image_ids)

    result: dict[str, dict[str, set[int]]] = {
        key: {} for key in SEARCH_CATEGORY_DEFS if key != "person"
    }
    for category, tag_map in SEARCH_TAG_ALIASES.items():
        for label, aliases in tag_map.items():
            ids: set[int] = set()
            for value in (label, *aliases):
                ids.update(normalized_raw.get(normalize_tag_text(value), set()))
            if ids:
                result[category][label] = ids
    return result


def searchable_aliases(query: str) -> tuple[str, ...]:
    matches = match_canonical_tag(query)
    if len(matches) == 1:
        category, label = matches[0]
        return tuple(dict.fromkeys((label, *SEARCH_TAG_ALIASES[category][label])))
    if matches:
        category, label = matches[0]
        if normalize_tag_text(query) in {
            normalize_tag_text(label),
            *(normalize_tag_text(v) for v in SEARCH_TAG_ALIASES[category][label]),
        }:
            return tuple(dict.fromkeys((label, *SEARCH_TAG_ALIASES[category][label])))
    clean = str(query or "").strip()
    return (clean,) if clean else ()
