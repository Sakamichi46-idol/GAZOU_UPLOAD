SAKAMICHI_FULL_NAME_SURNAME_READINGS: dict[str, str] = {
    '上村莉菜': 'うえむら',
    '上村ひなの': 'かみむら',
}

def member_surname_kana_sort_key(name: str) -> tuple[str, str]:
    """メンバー名を名字の読み仮名ベースの五十音順で並べるキーを返す。"""
    text = str(name or "").strip()
    if not text:
        return ("", "")

    explicit = SAKAMICHI_FULL_NAME_SURNAME_READINGS.get(text)
    if explicit:
        return (explicit, text)

    for surname in sorted(SAKAMICHI_SURNAME_READINGS, key=len, reverse=True):
        if text.startswith(surname):
            return (SAKAMICHI_SURNAME_READINGS[surname], text)

    return (text, text)

